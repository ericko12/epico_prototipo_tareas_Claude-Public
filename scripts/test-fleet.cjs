const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const ts = require('typescript');
const path = require('node:path');
const filename = path.resolve(__dirname, '../features/parqueVehicular/domain/fleet.ts');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } });
const mod = new Module(filename, module);
mod._compile(compiled.outputText, filename);
const f = mod.exports;
assert.equal(f.assignedAddresses('529').length, 2, 'Oculta la tercera dirección asignada a otro asesor');
assert.equal(f.canAccessAddress('529-MTY'), false);
assert.equal(f.visibleCustomers().some(c => c.id === 'not-in-portfolio'), false, 'Oculta clientes sin direcciones en cartera');
assert.ok(f.assignedAddresses('529').every(a => a.customerId === '529'));
assert.equal(f.assignedAddresses('529', '53').length, 1);
assert.equal(f.validStoredFleets(f.INITIAL_FLEETS), true);
assert.equal(f.validStoredFleets([{ ...f.INITIAL_FLEETS[0], addressId: '529-MTY' }]), false, 'Rechaza persistencia fuera de cartera');
assert.equal(f.validStoredFleets([{ id: 'incompleto' }]), false);
const sample = f.INITIAL_FLEETS[0];
assert.equal(Object.keys(f.validateFleet(sample)).length, 0);
assert.ok(f.validateFleet({ ...sample, brand: 'VOLVO' }).brand);
assert.ok(f.validateFleet({ ...sample, model: 'T680' }).model);
for (const units of ['0', '-1', '2.5', 'abc']) assert.ok(f.validateFleet({ ...sample, units }).units);
assert.ok(f.validateFleet({ ...sample, from: '2020', to: '2010' }).from);
assert.ok(f.validateFleet({ ...sample, from: '20' }).from);
assert.equal(Object.keys(f.validateFleet({ ...sample, from: '', to: '', motor: '' })).length, 0, 'Opcionales en esta propuesta');
assert.equal(f.hasBody('Servicio pesado'), false);
assert.equal(f.hasBody('Autobús – Transporte público o de personal'), true);
assert.equal(f.sameConfiguration(sample, { ...sample, units: '100' }), true, 'Cantidad distinta no evita coincidencia de configuración');
assert.equal(f.sameConfiguration(sample, { ...sample, motor: 'D13' }), false);
console.log('Pruebas de cartera, contexto, catálogos y validaciones del parque vehicular aprobadas.');
